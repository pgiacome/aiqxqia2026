"""Turn the newest experiment outputs into LaTeX macros for the manuscript.

The paper never hard-codes a numeral that came from an experiment. It uses the macros
this script writes, so a rerun that changes a number changes the paper too, and a stale
claim becomes a compile-time undefined-macro error rather than a silent lie.

Every macro is emitted with ``\\providecommand`` plus ``\\renewcommand`` so the file is
idempotent and the manuscript still compiles if a macro is later dropped.
"""

from __future__ import annotations

import argparse
import json
import logging
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)

__all__ = ["collect", "dataset_table", "e1_table", "e2_table", "fmt"]


def _newest(root: Path, prefix: str) -> dict[str, Any]:
    candidates = sorted(root.glob(f"{prefix}_*/results.json"))
    if not candidates:
        raise FileNotFoundError(f"no results for {prefix} under {root}; run the experiment first")
    logger.info("Reading %s", candidates[-1])
    return json.loads(candidates[-1].read_text(encoding="utf-8"))


def fmt(value: float | int | None, digits: int = 3) -> str:
    """Format a number for LaTeX maths mode, using scientific notation when it helps."""
    if value is None:
        return r"\text{n/a}"
    if isinstance(value, int) or float(value).is_integer():
        return f"{int(value):,}".replace(",", r"\,")
    value = float(value)
    if value == 0:
        return "0"
    if abs(value) < 1e-3 or abs(value) >= 1e4:
        mantissa, exponent = f"{value:.{digits - 1}e}".split("e")
        return rf"{mantissa} \times 10^{{{int(exponent)}}}"
    return f"{value:.{digits}g}"


def _macro(name: str, value: str) -> str:
    return f"\\providecommand{{\\{name}}}{{}}\\renewcommand{{\\{name}}}{{{value}}}"


def collect(outputs: Path) -> list[str]:
    """Build the macro list from the newest run of each experiment."""
    lines = [
        "% Generated by code/experiments/collect_numbers.py -- do not edit by hand.",
        "% Rerun: uv run python -m experiments.collect_numbers",
    ]

    e1 = _newest(outputs, "e1_ultrametricity")
    by_name = {r["encoding"]: r for r in e1["records"] if "violations" in r}
    path, basis = by_name["path_state"], by_name["basis"]
    lines += [
        _macro("EOneDataset", str(e1["dataset"])),
        _macro("EOneLeaves", fmt(e1["leaves"])),
        _macro("EOneHeight", fmt(e1["tree_height"])),
        _macro("EOneSourceNodes", fmt(e1["source_nodes"])),
        _macro("EOneSourceHeight", fmt(e1["source_height"])),
        _macro("EOneLevels", fmt(e1["max_resolution_depth"])),
        _macro("PathStateNodes", fmt(e1["tree_nodes"])),
        _macro("PathStateQubits", fmt(e1["path_state_qubits"])),
        _macro("PathResidual", fmt(path["profile_residual"])),
        _macro("PathViolations", fmt(path["violations"])),
        _macro("PathLevelConstancy", fmt(path["level_constancy"])),
        _macro("PathResolution", fmt(path["resolution_depth"])),
        _macro("BasisViolations", fmt(basis["violations"])),
        _macro("BasisResolution", fmt(basis["resolution_depth"])),
    ]
    for label, macro in (("angle", "Angle"), ("zz", "ZZ"), ("random_product", "RandProd")):
        if label in by_name:
            lines += [
                _macro(f"{macro}ViolationRate", fmt(by_name[label]["violation_rate"])),
                _macro(f"{macro}LevelConstancy", fmt(by_name[label]["level_constancy"])),
            ]
    if "rbf_integer" in by_name:
        lines.append(_macro("RBFViolations", fmt(by_name["rbf_integer"]["violations"])))

    for run in _all_runs(outputs, "e1_ultrametricity"):
        if run.get("dataset") == "ncbi":
            lines.append(_macro("NCBIRadix", fmt(run["radix"])))

    e2 = _newest(outputs, "e2_classification")
    e2_by = {r["encoding"]: r for r in e2["records"] if "leaf_accuracy" in r}
    best = max(e2_by.values(), key=lambda r: r["leaf_accuracy"])
    lines += [
        _macro("ETwoLeaves", fmt(e2["leaves_used"])),
        _macro("ETwoClasses", fmt(e2["fine_classes"])),
        _macro("ETwoPathAccuracy", fmt(e2_by["path_state"]["leaf_accuracy"])),
        _macro("ETwoPathAccuracyStd", fmt(e2_by["path_state"]["leaf_accuracy_std"])),
        _macro("ETwoPathRho", fmt(e2_by["path_state"]["spearman_rho"])),
        _macro("ETwoBestBaseline", str(best["encoding"]).replace("_", " ")),
        _macro("ETwoBestBaselineAccuracy", fmt(best["leaf_accuracy"])),
        _macro("ETwoBestBaselineRho", fmt(best["spearman_rho"])),
    ]

    e3 = _newest(outputs, "e3_ablations")
    worst = max(r["profile_residual"] for r in e3["records"])
    lines += [
        _macro("EThreeConfigs", fmt(len(e3["records"]))),
        _macro("EThreeWorstResidual", fmt(worst)),
        _macro("EThreeMaxViolations", fmt(max(r["violations"] for r in e3["records"]))),
    ]
    for p in (2, 3, 5):
        sel = [
            r
            for r in e3["records"]
            if r["radix"] == p and r["profile"] == "geometric_2.0" and r["depth"] == 5
        ]
        if sel:
            bound = sel[0]["qubit_lower_bound_full_tree"]
            lines.append(_macro(f"QubitBoundP{_word(p)}", fmt(bound)))

    e4 = _newest(outputs, "e4_entangling")
    lines += [
        _macro("EFourConfigs", fmt(len(e4["records"]))),
        _macro("EFourExactAlignment", fmt(e4["exact_point"]["alignment"])),
        _macro("EFourBestAlignment", fmt(e4["best_alignment"]["alignment"])),
        _macro("EFourBestDistortion", fmt(e4["best_alignment"]["distortion"])),
        _macro("EFourAlignmentGain", fmt(e4["alignment_gain_over_exact"])),
    ]

    e5 = _newest(outputs, "e5_noise")
    lines += [
        _macro("ShotBudget", fmt(e5["shot_budget"])),
        _macro("ShotTargetExcess", fmt(e5["target_excess"])),
        _macro("TieFraction", fmt(e5["tie_fraction"])),
        _macro("ENoiseRepeats", fmt(e5["repeats"])),
    ]
    decay = sorted(
        (r for r in e5["records"] if r["depolarising_rate"] == 0.0 and r["shots"] != "exact"),
        key=lambda r: int(r["shots"]),
    )
    if decay:
        lines += [
            _macro("ExcessAtLowShots", fmt(decay[0]["max_excess_mean"])),
            _macro("ExcessAtLowShotsCount", fmt(int(decay[0]["shots"]))),
            _macro("ExcessAtHighShots", fmt(decay[-1]["max_excess_mean"])),
            _macro("ExcessAtHighShotsCount", fmt(int(decay[-1]["shots"]))),
        ]
    return lines


def _word(n: int) -> str:
    """LaTeX macro names cannot contain digits."""
    return {2: "Two", 3: "Three", 5: "Five"}[n]


def _all_runs(outputs: Path, prefix: str) -> list[dict[str, Any]]:
    """Every run of an experiment, newest per dataset, oldest first."""
    by_dataset: dict[str, dict[str, Any]] = {}
    for path in sorted(outputs.glob(f"{prefix}_*/results.json")):
        payload = json.loads(path.read_text(encoding="utf-8"))
        by_dataset[str(payload.get("dataset", path.parent.name))] = payload
    order = ["synthetic", "wordnet", "go", "ncbi"]
    return [by_dataset[d] for d in order if d in by_dataset]


PRETTY = {
    "synthetic": r"synthetic $2$-ary",
    "wordnet": "WordNet",
    "go": "Gene Ontology",
    "ncbi": "NCBI Mammalia",
    "path_state": "path state (ours)",
    "angle": "angle",
    "basis": "basis",
    "zz": "ZZ / IQP",
    "random_product": "random product",
    "block_product": "block product",
    "rbf_integer": "RBF (integer)",
    "rbf_onehot": "RBF (one-hot)",
}


def _pivot(runs, encodings, metrics, header):
    """Encodings as rows, datasets as column groups. Far more compact than the
    dataset-major layout, which needs one row per (dataset, encoding) pair."""
    ncols = len(runs) * len(metrics)
    rows = ["\\begin{tabular}{l" + "r" * ncols + "}", "\\toprule"]
    groups = " & ".join(
        f"\\multicolumn{{{len(metrics)}}}{{c}}{{{PRETTY[str(r['dataset'])]}}}" for r in runs
    )
    rows.append(f"encoding & {groups} \\\\")
    spans = []
    col = 2
    for _ in runs:
        spans.append(f"\\cmidrule(lr){{{col}-{col + len(metrics) - 1}}}")
        col += len(metrics)
    rows.append("".join(spans))
    rows.append("& " + " & ".join(header * len(runs)) + " \\\\")
    rows.append("\\midrule")
    for name in encodings:
        label = PRETTY[name]
        if name == "path_state":
            label = f"\\textbf{{{label}}}"
        cells = []
        for run in runs:
            rec = next((r for r in run["records"] if r.get("encoding") == name), None)
            for _metric, fmt_cell in metrics:
                cells.append("---" if rec is None else fmt_cell(rec, run))
        rows.append(f"{label} & " + " & ".join(cells) + " \\\\")
    rows.append("\\bottomrule")
    rows.append("\\end{tabular}")
    return "\n".join(rows)


def e1_table(outputs: Path) -> str:
    """Level constancy and resolution depth, encodings by dataset.

    Real hierarchies only: the synthetic trees get a systematic sweep in E3, and
    including them here makes the table overrun the text block.
    """
    runs = [r for r in _all_runs(outputs, "e1_ultrametricity") if r["dataset"] != "synthetic"]
    metrics = [
        ("level_constancy", lambda r, run: f"${fmt(r['level_constancy'], 2)}$"),
        (
            "resolution_depth",
            lambda r, run: f"{r['resolution_depth']}/{run['max_resolution_depth']}",
        ),
    ]
    return _pivot(
        runs,
        ["path_state", "basis", "angle", "zz", "random_product"],
        metrics,
        ["l.c.", "res."],
    )


def e2_table(outputs: Path) -> str:
    """Leaf accuracy and Spearman rho, encodings by dataset (real hierarchies only)."""
    runs = [r for r in _all_runs(outputs, "e2_classification") if r["dataset"] != "synthetic"]
    metrics = [
        ("leaf_accuracy", lambda r, run: f"${fmt(r['leaf_accuracy'], 2)}$"),
        (
            "spearman_rho",
            lambda r, run: "---"
            if r["spearman_rho"] is None
            else f"${fmt(r['spearman_rho'], 2)}$",
        ),
    ]
    return _pivot(
        runs,
        ["path_state", "angle", "zz", "random_product", "basis", "rbf_integer"],
        metrics,
        ["acc.", "$\\rho$"],
    )


def dataset_table(outputs: Path) -> str:
    """Shapes of the four hierarchies after the preprocessing pipeline."""
    runs = _all_runs(outputs, "e1_ultrametricity")
    rows = ["\\begin{tabular}{lrrrrrr}", "\\toprule",
            "dataset & source nodes & source height & sampled leaves & nodes & "
            "radix & qubits \\\\", "\\midrule"]
    for run in runs:
        rows.append(
            f"{PRETTY[str(run['dataset'])]} & ${fmt(run['source_nodes'])}$ & "
            f"${fmt(run['source_height'])}$ & ${fmt(run['leaves'])}$ & "
            f"${fmt(run['tree_nodes'])}$ & ${fmt(run['radix'])}$ & "
            f"${fmt(run['path_state_qubits'])}$ \\\\"
        )
    rows.append("\\bottomrule")
    rows.append("\\end{tabular}")
    return "\n".join(rows)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--outputs", type=Path, default=Path("outputs"))
    parser.add_argument("--target", type=Path, default=Path("papers/aiqxqia2026/numbers.tex"))
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")

    lines = collect(args.outputs)
    args.target.parent.mkdir(parents=True, exist_ok=True)
    args.target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    logger.info("Wrote %d macros to %s", len(lines) - 2, args.target)

    tables = args.target.parent / "tables"
    tables.mkdir(exist_ok=True)
    banner = "% Generated by code/experiments/collect_numbers.py -- do not edit.\n"
    for name, builder in (
        ("e1-ultrametricity", e1_table),
        ("e2-accuracy", e2_table),
        ("datasets", dataset_table),
    ):
        (tables / f"{name}.tex").write_text(banner + builder(args.outputs) + "\n", "utf-8")
        logger.info("Wrote %s", tables / f"{name}.tex")


if __name__ == "__main__":
    main()
